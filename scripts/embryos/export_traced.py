"""Export the traced Theiler plates to src/library/items/embryos/traced.ts, with gridded previews for placing
features (features.ts). Run scripts/embryos/run.sh to download the plates, trace them and export.
Usage: python export_traced.py <out.ts> <previewDir>"""
import sys, os, json, math
import numpy as np
from PIL import Image, ImageDraw, ImageFont
HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.join(HERE, 'work')
# stage -> (theiler plate, crown-rump length mm (Theiler/Kaufman, approximate))
STAGES = [('E10.5', 17, 4.0), ('E11.5', 19, 5.5), ('E12.5', 20, 7.5), ('E13.5', 21, 9.5), ('E14.5', 22, 11.0), ('E15.5', 23, 13.0), ('E16.5', 24, 15.5), ('E17.5', 25, 18.0), ('E18.5', 26, 21.0)]
UNITS_PER_MM = 8.0
def catmull(pts, closed):
    n = len(pts)
    at = lambda i: pts[(i % n + n) % n] if closed else pts[min(n - 1, max(0, i))]
    f = lambda v: f'{v:.1f}'.replace('.0', '') if False else f'{v:.1f}'
    d = f'M{pts[0][0]:.1f} {pts[0][1]:.1f}'
    for i in range(n if closed else n - 1):
        p0, p1, p2, p3 = at(i - 1), at(i), at(i + 1), at(i + 2)
        d += f'C{p1[0] + (p2[0] - p0[0]) / 6:.1f} {p1[1] + (p2[1] - p0[1]) / 6:.1f} {p2[0] - (p3[0] - p1[0]) / 6:.1f} {p2[1] - (p3[1] - p1[1]) / 6:.1f} {p2[0]:.1f} {p2[1]:.1f}'
    return d + ('z' if closed else '')
out_ts, prev = sys.argv[1], sys.argv[2]
os.makedirs(prev, exist_ok=True)
entries = []
for stage, ts, crl in STAGES:
    j = json.load(open(f'{WORK}/ts{ts}.json'))
    x0, y0, x1, y1 = j['bbox']
    # the longest extent of the silhouette is taken as the crown-rump length
    extent = max(x1 - x0, y1 - y0)
    u = crl * UNITS_PER_MM / extent
    m = 2.0  # margin units
    sx = lambda x: (x - x0) * u + m
    sy = lambda y: (y - y0) * u + m
    W = (x1 - x0) * u + 2 * m; H = (y1 - y0) * u + 2 * m
    body = catmull([(sx(x), sy(y)) for x, y in j['silhouette']], True)
    lines = []
    sil = np.array(j['silhouette'], float)
    def dist_to_sil(p):
        q = np.array(p, float); d = sil - q
        return float(np.sqrt((d * d).sum(1)).min())
    for c in j['creases']:
        L = sum(math.hypot(c[i + 1][0] - c[i][0], c[i + 1][1] - c[i][1]) for i in range(len(c) - 1))
        if L * u < 2.5: continue
        # a line that hugs the silhouette is the plate's double contour, not a feature
        if all(dist_to_sil(p) * u < 1.3 for p in c): continue
        lines.append(catmull([(sx(x), sy(y)) for x, y in c], False))
    entries.append((stage, ts, crl, W, H, body, lines))
    # preview: original drawing scaled to units at 6 px/unit with the traced paths and a 10-unit grid
    px = 6
    img = Image.open(f'{WORK}/ts{ts}_1B.png').convert('RGB')
    # drawing coordinates were traced at 3x; bbox is in 3x pixels
    crop = img.resize((img.width * 3, img.height * 3), Image.LANCZOS).crop((x0 - int(m / u), y0 - int(m / u), x1 + int(m / u), y1 + int(m / u)))
    crop = crop.resize((int(W * px), int(H * px)), Image.LANCZOS)
    dr = ImageDraw.Draw(crop)
    for gx in range(0, int(W) + 1, 10):
        dr.line([(gx * px, 0), (gx * px, H * px)], fill=(120, 170, 255), width=1); dr.text((gx * px + 2, 2), str(gx), fill=(0, 0, 200))
    for gy in range(0, int(H) + 1, 10):
        dr.line([(0, gy * px), (W * px, gy * px)], fill=(120, 170, 255), width=1); dr.text((2, gy * px + 2), str(gy), fill=(0, 0, 200))
    sil = [(sx(x) * px, sy(y) * px) for x, y in j['silhouette']]
    dr.line(sil + [sil[0]], fill=(220, 40, 40), width=2)
    for c in j['creases']:
        pts = [(sx(x) * px, sy(y) * px) for x, y in c]
        if len(pts) > 1: dr.line(pts, fill=(40, 160, 60), width=2)
    crop.save(f'{prev}/{stage.replace(".", "")}_grid.png')
    print(stage, 'TS', ts, 'viewBox', round(W, 1), round(H, 1), 'lines', len(lines))
ts = ['/**', ' * Embryo silhouettes and feature lines traced from the eMouseAtlas Theiler stage plates', ' * (https://www.emouseatlas.org/emap/ema/theiler_stages/, CC BY 3.0), scaled to 8 units per mm of', ' * crown-rump length. Generated by the tracing scripts described in', ' * docs/superpowers/specs/2026-10-14-drawing-styles-design.md ("Reference-traced embryos"). Do not edit by hand.', ' */', "import type { Stage } from '../limbs/types'", '', 'export interface TracedEmbryo {', '  theiler: number', '  /** crown-rump length in mm used for the scale */', '  crl: number', '  viewBox: string', '  /** closed silhouette path */', '  body: string', '  /** open feature lines (limb edges, eye, ear, mouth) from the plate */', '  lines: string[]', '}', '', 'export const TRACED: Record<Stage, TracedEmbryo> = {']
for stage, t, crl, W, H, body, lines in entries:
    ts.append(f"  '{stage}': {{ theiler: {t}, crl: {crl}, viewBox: '0 0 {W:.1f} {H:.1f}', body: '{body}', lines: [{', '.join(repr(l) for l in lines)}] }},")
ts.append('}')
open(out_ts, 'w').write('\n'.join(ts) + '\n')
print('wrote', out_ts, os.path.getsize(out_ts), 'bytes')
